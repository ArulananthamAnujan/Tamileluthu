// Writes the SQL that loads the workbook practice games into the database.
//   node scripts/practice-seed.mjs          rewrite the migration file
//   node scripts/practice-seed.mjs --check  fail if the file is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { SETS } from '../supabase/practice/workbook.mjs';
import { checkSet } from '../src/lib/practice.js';

export const SEED_FILE = fileURLToPath(new URL('../supabase/migrations/20261115000001_practice_workbook.sql', import.meta.url));
const q = (s) => `'${String(s ?? '').replace(/'/g, "''")}'`;

export function seedSql(sets = SETS) {
  const problems = sets.flatMap(checkSet);
  if (problems.length) throw new Error('Fix these first:\n' + problems.join('\n'));
  const rows = sets.map((s) => `  (${[q(s.slug), s.stage, s.sort, q(s.topic), q(s.topic_ta), q(s.title), q(s.title_ta), q(s.intro), q(s.intro_ta), q(s.source)].join(', ')},\n   ${q(JSON.stringify(s.items))}::jsonb)`);
  return `-- Practice games from the VCE Tamil Writing Practice Workbook (Units 3 and 4).
-- GENERATED by scripts/practice-seed.mjs from supabase/practice/workbook.mjs. Do not edit by hand.
-- Apply AFTER 20261115000000_homework_files_practice.sql. Safe to run again: games are updated in place.
-- The games stay hidden: only school admins can see them until an admin gives them to teachers.
insert into public.practice_sets (slug, stage, sort, topic, topic_ta, title, title_ta, intro, intro_ta, source, items) values
${rows.join(',\n')}
on conflict (slug) do update set
  stage = excluded.stage, sort = excluded.sort, topic = excluded.topic, topic_ta = excluded.topic_ta,
  title = excluded.title, title_ta = excluded.title_ta, intro = excluded.intro, intro_ta = excluded.intro_ta,
  source = excluded.source, items = excluded.items, updated_at = now();
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const sql = seedSql();
  if (process.argv.includes('--check')) {
    if (readFileSync(SEED_FILE, 'utf8') !== sql) { console.error('The seed file is out of date. Run: node scripts/practice-seed.mjs'); process.exit(1); }
    console.log('Seed file is up to date.');
  } else {
    writeFileSync(SEED_FILE, sql);
    console.log(`Wrote ${SETS.length} games, ${SETS.reduce((n, s) => n + s.items.length, 0)} questions.`);
  }
}
